// Formatting helpers (duration display, etc.).

// Duration strings from the backend are already normalized ("3:42", "1:02:31").
// This is a small safety net in case a raw number of seconds sneaks in.
export function formatDuration(duration) {
  if (!duration) return '0:00';
  if (typeof duration === 'number') {
    const s = Math.max(0, Math.floor(duration));
    const h = Math.floor(s / 3600);
    const m = Math.floor((s % 3600) / 60);
    const sec = s % 60;
    if (h > 0) return `${h}:${m.toString().padStart(2, '0')}:${sec.toString().padStart(2, '0')}`;
    return `${m}:${sec.toString().padStart(2, '0')}`;
  }
  return String(duration);
}

export function formatTime(seconds) {
  if (!Number.isFinite(seconds) || seconds < 0) return '0:00';
  const s = Math.floor(seconds);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = s % 60;
  if (h > 0) return `${h}:${m.toString().padStart(2, '0')}:${sec.toString().padStart(2, '0')}`;
  return `${m}:${sec.toString().padStart(2, '0')}`;
}

export function parseDurationToSeconds(duration) {
  if (!duration || typeof duration === 'number') return Number(duration) || 0;
  const parts = String(duration).split(':').map((n) => parseInt(n, 10) || 0);
  if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
  if (parts.length === 2) return parts[0] * 60 + parts[1];
  return parts[0] || 0;
}
